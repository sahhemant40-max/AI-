import pytest
from httpx import AsyncClient, ASGITransport
from backend.app.main import app
from backend.app.database.session import connect_to_mongo, close_mongo_connection


@pytest.mark.asyncio
async def test_full_security_scan_and_reporting_pipeline():
    await connect_to_mongo()
    try:
        async with AsyncClient(transport=ASGITransport(app=app), base_url="http://test") as client:
            # 1. Register a test model
            model_payload = {
                "name": "AuditTarget-LLM-Classifier",
                "model_type": "LLM",
                "description": "Customer inquiry routing and risk classification model.",
                "version": "2.0.0",
                "framework": "PyTorch",
                "owner": "Security Engineering",
                "environment": "Production",
                "intended_use": "Customer support routing",
                "risk_category": "High",
            }
            model_resp = await client.post("/api/models", json=model_payload)
            assert model_resp.status_code == 201
            model_id = model_resp.json()["id"]

            # 2. Execute full scan across all 4 modules
            scan_payload = {
                "name": "Comprehensive-SecOps-Audit-01",
                "model_id": model_id,
                "intensity": "comprehensive",
                "modules": ["robustness", "fairness", "privacy", "llm_security"],
                "parameters": {
                    "epsilon": 0.12,
                    "sensitive_attribute": "gender",
                },
            }
            scan_resp = await client.post("/api/scans", json=scan_payload)
            assert scan_resp.status_code == 201
            scan_data = scan_resp.json()
            scan_id = scan_data["id"]
            assert scan_data["status"] == "completed"
            assert scan_data["progress_percentage"] == 100
            assert 0 <= scan_data["risk_score"] <= 100
            assert scan_data["risk_category"] in ["Low", "Medium", "High", "Critical"]
            assert "results" in scan_data
            assert "robustness" in scan_data["results"]
            assert "fairness" in scan_data["results"]
            assert "privacy" in scan_data["results"]
            assert "llm_security" in scan_data["results"]

            # 3. Retrieve findings generated by the scan
            findings_resp = await client.get(f"/api/findings?scan_id={scan_id}")
            assert findings_resp.status_code == 200
            findings_list = findings_resp.json()
            assert isinstance(findings_list, list)

            if len(findings_list) > 0:
                finding_id = findings_list[0]["id"]
                # Update status
                patch_resp = await client.patch(
                    f"/api/findings/{finding_id}",
                    json={"status": "in_progress", "remediation_notes": "Reviewed by security team"}
                )
                assert patch_resp.status_code == 200
                assert patch_resp.json()["status"] == "in_progress"

            # 4. Generate Audit Report
            report_payload = {
                "scan_id": scan_id,
                "report_type": "Comprehensive Technical Audit",
                "title": "Automated Security Assessment Dossier",
            }
            report_resp = await client.post("/api/reports", json=report_payload)
            assert report_resp.status_code == 201
            report_data = report_resp.json()
            report_id = report_data["id"]

            # 5. Download and verify PDF
            pdf_resp = await client.get(f"/api/reports/{report_id}/download?format=pdf")
            assert pdf_resp.status_code == 200
            assert pdf_resp.content.startswith(b"%PDF")

            # 6. Download and verify DOCX
            docx_resp = await client.get(f"/api/reports/{report_id}/download?format=docx")
            assert docx_resp.status_code == 200
            assert docx_resp.content.startswith(b"PK")  # ZIP header for DOCX

            # 7. Verify NIST AI RMF Compliance endpoint
            comp_resp = await client.get("/api/compliance")
            assert comp_resp.status_code == 200
            comp_data = comp_resp.json()
            assert "GOVERN" in comp_data["functions"]
            assert "MEASURE" in comp_data["functions"]
            assert comp_data["implemented_count"] > 0
    finally:
        await close_mongo_connection()
